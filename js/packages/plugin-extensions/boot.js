// Pre-boot work of the android entry (bundle-android/main.mjs), synchronous and node:-only so
// it adds next to nothing to cold start. Also the shared reader/writer of the engine-side
// extension state used by index.js.
//
// Files (ENGINE-CONTRACT §2.6, docs/PLUGINS-CONTRACT.md):
//   $DSH_HOME/android/extensions-state.json   suspended bundles, safe mode, install sources, ask-before-call
//   $DSH_HOME/android/boot-journal.json       last boots: booting → ready | stopped
//   $DSH_HOME/android/last-crash.json         the last fatal error and the packages on its stack
//   $DSH_HOME/android/app-layer.patch.yml     the app's settings layer (a launcher --patch overlay)
//   $DSH_HOME/profiles/android/{pnpm-workspace.yaml,.pnpmfile.cjs}   kept in shape at every boot
import { appendFileSync, existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/** The three bundles every android profile starts with; everything else is a third-party plugin. */
export const BUILTIN_BUNDLES = Object.freeze(['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-sdk-app', '@dsh-android/bundle-android'])
/** First line of the profile patch the app generated before the overlay existed. */
export const LEGACY_APP_HEADER = '# Generated by DSH-Android'
const JOURNAL_KEEP = 8
/** Consecutive boots that never became ready before the next one starts in safe mode. */
export const SAFE_MODE_AFTER = 2

export const HERE = dirname(fileURLToPath(import.meta.url))

/** Every path the engine side of extensions uses, from the environment. */
export function paths(env = process.env) {
  const home = env.DSH_HOME || join(homedir(), '.dsh')
  const engineDir = resolve(HERE, '../../..')
  const android = join(home, 'android')
  const cache = env.DSH_ANDROID_CACHE_DIR || join(tmpdir(), 'dsh-pnpm')
  return {
    home,
    engineDir,
    android,
    profile: join(home, 'profiles', 'android'),
    state: join(android, 'extensions-state.json'),
    journal: join(android, 'boot-journal.json'),
    crash: join(android, 'last-crash.json'),
    overlay: join(android, 'app-layer.patch.yml'),
    pnpmReport: join(android, 'pnpm-report.jsonl'),
    skills: join(home, 'skills'),
    skillsDisabled: join(home, 'skills-disabled'),
    mcpServers: join(home, 'mcp-servers'),
    cache,
    store: join(cache, 'store'),
    staging: join(cache, 'ext-staging'),
    pnpm: join(engineDir, 'node_modules', 'pnpm', 'bin', 'pnpm.mjs'),
    preload: join(engineDir, 'node_modules', '@dsh-android', 'bundle-android', 'android-env.cjs'),
    gate: join(HERE, 'pnpmfile.cjs'),
  }
}

export function readJson(file, fallback) {
  try { return JSON.parse(readFileSync(file, 'utf8')) } catch { return fallback }
}

export function writeJson(file, value) {
  mkdirSync(dirname(file), { recursive: true })
  const tmp = `${file}.${process.pid}.tmp`
  writeFileSync(tmp, JSON.stringify(value, null, 2) + '\n', { mode: 0o600 })
  renameSync(tmp, file)
}

const EMPTY_STATE = () => ({ version: 1, suspended: {}, safeMode: { active: false, savedBundles: [] }, installedFrom: {}, askBeforeCall: [], pendingRemoval: [], updates: { checkedAt: 0, latest: {} }, notices: [] })

export function readState(p = paths()) {
  const s = { ...EMPTY_STATE(), ...readJson(p.state, {}) }
  for (const [k, v] of Object.entries(EMPTY_STATE())) if (typeof s[k] !== typeof v || Array.isArray(s[k]) !== Array.isArray(v)) s[k] = v
  return s
}

export function writeState(state, p = paths()) { writeJson(p.state, state) }

export function readManifest(p = paths()) { return readJson(join(p.profile, 'package.json'), undefined) }

export function bundlesOf(manifest) {
  const b = manifest?.dsh?.profile?.bundles
  return Array.isArray(b) ? b.filter(x => typeof x === 'string') : []
}

export function writeBundles(manifest, bundles, p = paths()) {
  manifest.dsh = { ...manifest.dsh, profile: { ...manifest.dsh?.profile, bundles } }
  writeJson(join(p.profile, 'package.json'), manifest)
}

export const isThirdParty = name => !BUILTIN_BUNDLES.includes(name)

/** The curated DSH-Android plugin index (format 1, dsh's plugin market). */
export const DEFAULT_INDEXES = Object.freeze(['https://cdn.jsdelivr.net/gh/jackwener/DeepseekHarness-Android@main/plugins/index.json'])
export const NPMJS = 'https://registry.npmjs.org/'
export const NPMMIRROR = 'https://registry.npmmirror.com/'

/** Mainland-China locale or time zone: npmmirror first. */
export function prefersMirror(env = process.env) {
  return /^zh(-Hans)?(-CN)?$|^zh-(Hans-)?CN/i.test(env.DSH_ANDROID_LOCALE || '') || /^Asia\/(Shanghai|Chongqing|Chungking|Urumqi|Harbin)$/.test(env.DSH_ANDROID_TZ || env.TZ || '')
}

/**
 * dsh plugin manager `registry` / `fallbackRegistries`: the app's choice (DSH_PLUGIN_REGISTRY,
 * DSH_PLUGIN_FALLBACK_REGISTRIES comma-separated, empty = none), else by region, each official
 * registry falling back to the other.
 */
export function registryPlanFromEnv(env = process.env) {
  const mirror = prefersMirror(env)
  const registry = env.DSH_PLUGIN_REGISTRY || (mirror ? NPMMIRROR : NPMJS)
  const fallbackRegistries = env.DSH_PLUGIN_FALLBACK_REGISTRIES !== undefined
    ? env.DSH_PLUGIN_FALLBACK_REGISTRIES.split(',').map(x => x.trim()).filter(Boolean)
    : [registry === NPMJS ? NPMMIRROR : NPMJS]
  return { registry, fallbackRegistries: fallbackRegistries.filter(r => r !== registry) }
}

// ── crash attribution ───────────────────────────────────────────────────────

/** Package names (outermost first) whose files appear on [stack] under [nodeModules]. */
export function packagesOnStack(stack, nodeModules) {
  const out = []
  const marker = nodeModules.replace(/\/+$/, '') + '/'
  for (const line of String(stack ?? '').split('\n')) {
    let text = line
    try { text = decodeURIComponent(line) } catch {}
    let i = text.indexOf(marker)
    if (i < 0) continue
    let rest = text.slice(i + marker.length)
    // nested node_modules (a dependency of a dependency): the outermost package owns the file
    const parts = rest.split('/')
    const name = parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0]
    if (name && !name.startsWith('.') && !out.includes(name)) out.push(name)
  }
  return out
}

/** The selected third-party bundles whose installed dependency closure contains [pkg]. */
export function bundlesOwning(pkg, bundles, nodeModules) {
  const manifestOf = name => readJson(join(nodeModules, name, 'package.json'), undefined)
  const owners = []
  for (const bundle of bundles) {
    const seen = new Set()
    const queue = [bundle]
    while (queue.length > 0) {
      const name = queue.shift()
      if (seen.has(name)) continue
      seen.add(name)
      const m = manifestOf(name)
      if (m === undefined) continue
      for (const dep of Object.keys({ ...m.dependencies, ...m.optionalDependencies })) queue.push(dep)
    }
    if (seen.has(pkg)) owners.push(bundle)
  }
  return owners
}

/** The single third-party bundle a crash stack points at, or undefined. */
export function attributeCrash(stack, bundles, nodeModules) {
  const thirdParty = bundles.filter(isThirdParty)
  for (const pkg of packagesOnStack(stack, nodeModules)) {
    const owners = thirdParty.includes(pkg) ? [pkg] : bundlesOwning(pkg, thirdParty, nodeModules)
    if (owners.length === 1) return { bundle: owners[0], package: pkg }
    if (owners.length > 1) return undefined
  }
  return undefined
}

// ── profile preparation ─────────────────────────────────────────────────────

const WORKSPACE_KEYS = p => ({
  nodeLinker: 'hoisted',
  autoInstallPeers: 'false',
  packageImportMethod: 'copy',
  storeDir: JSON.stringify(p.store),
  // Install scripts never run on the phone (a native build cannot work there anyway).
  ignoreScripts: 'true',
})

/** Ensure our pnpm settings in a pnpm-workspace.yaml text, keeping every other line. */
export function withWorkspaceKeys(text, keys) {
  const lines = (text ?? 'packages:\n  - .\n').split('\n')
  for (const [key, value] of Object.entries(keys)) {
    const i = lines.findIndex(l => l.startsWith(`${key}:`))
    const line = `${key}: ${value}`
    if (i >= 0) lines[i] = line
    else {
      while (lines.length > 0 && lines.at(-1) === '') lines.pop()
      lines.push(line, '')
    }
  }
  return lines.join('\n')
}

export function pnpmfileText(gate) {
  return `// Written by the DSH-Android engine at every start: the phone compatibility gate of the\n// current engine (native modules refused, @deepseek-ai/* shared with the engine).\nmodule.exports = require(${JSON.stringify(gate)})\n`
}

/** A pnpm project directory with our workspace keys and gate (profile or MCP project). */
export function preparePnpmProject(dir, p, initialManifest) {
  mkdirSync(dir, { recursive: true })
  if (initialManifest !== undefined && !existsSync(join(dir, 'package.json'))) writeJson(join(dir, 'package.json'), initialManifest)
  const ws = join(dir, 'pnpm-workspace.yaml')
  let current
  try { current = readFileSync(ws, 'utf8') } catch {}
  const next = withWorkspaceKeys(current, WORKSPACE_KEYS(p))
  if (next !== current) writeFileSync(ws, next)
  const pf = join(dir, '.pnpmfile.cjs')
  const text = pnpmfileText(p.gate)
  let have
  try { have = readFileSync(pf, 'utf8') } catch {}
  if (have !== text) writeFileSync(pf, text)
}

/**
 * The app's settings layer moved from the profile patch to a launcher overlay. A profile
 * patch the app generated (its header) is backed up and emptied; if the overlay does not exist
 * yet its content becomes the overlay, so an update loses no provider settings.
 */
export function migrateAppLayer(p) {
  const patch = join(p.profile, 'cordis.patch.yml')
  let text
  try { text = readFileSync(patch, 'utf8') } catch { return undefined }
  if (!text.startsWith(LEGACY_APP_HEADER)) return undefined
  const backup = `${patch}.bak-${Date.now()}`
  writeFileSync(backup, text)
  if (!existsSync(p.overlay)) { mkdirSync(dirname(p.overlay), { recursive: true }); writeFileSync(p.overlay, text) }
  writeFileSync(patch, '# User layer of the android profile: plugin settings written by dsh (plugin manager,\n# config editor). The app\'s own settings live in $DSH_HOME/android/app-layer.patch.yml.\n[]\n')
  return backup
}

// ── node launcher / package manager ─────────────────────────────────────────

/** The node executable for child processes: DSH_NODE_BIN, the app's native dir, or this node (host). */
export function nodeBinary(env = process.env) {
  if (env.DSH_NODE_BIN) return env.DSH_NODE_BIN
  if (env.DSH_NATIVE_DIR) {
    const launcher = join(env.DSH_NATIVE_DIR, 'libdshnode.so')
    if (existsSync(launcher)) return launcher
  }
  return process.platform === 'android' ? join(env.DSH_NATIVE_DIR ?? '/nonexistent', 'libdshnode.so') : process.execPath
}

/** Node argv every child gets before its script: the AT_SECURE preload, a heap cap. */
export function childNodeArgs(p, heapMb = 384) {
  return [...(existsSync(p.preload) ? ['--require', p.preload] : []), `--max-old-space-size=${heapMb}`]
}

/** dsh's `profileContext.packageManager`: the bundled pnpm on the node launcher. */
export function packageManager(p, env = process.env) {
  const pm = join(p.cache, 'pnpm')
  return {
    command: nodeBinary(env),
    args: [...childNodeArgs(p), p.pnpm],
    env: {
      XDG_CACHE_HOME: join(pm, 'cache'),
      XDG_DATA_HOME: join(pm, 'data'),
      XDG_STATE_HOME: join(pm, 'state'),
      XDG_CONFIG_HOME: join(pm, 'config'),
      npm_config_update_notifier: 'false',
      PNPM_HOME: join(pm, 'home'),
      COREPACK_ENABLE_STRICT: '0',
      DSH_ANDROID_PNPM_REPORT: p.pnpmReport,
      // AT_SECURE children may ignore these; android-env.cjs restores them from process.env.
      ...env.TMPDIR ? { TMPDIR: env.TMPDIR } : {},
      ...env.NODE_EXTRA_CA_CERTS ? { NODE_EXTRA_CA_CERTS: env.NODE_EXTRA_CA_CERTS } : {},
      ...env.DSH_ANDROID_TZ ? { DSH_ANDROID_TZ: env.DSH_ANDROID_TZ } : {},
      ...proxyEnv(env),
    },
  }
}

export function proxyEnv(env = process.env) {
  const out = {}
  for (const k of ['HTTP_PROXY', 'HTTPS_PROXY', 'NO_PROXY', 'http_proxy', 'https_proxy', 'no_proxy']) if (env[k]) out[k] = env[k]
  return out
}

// ── the boot sequence ───────────────────────────────────────────────────────

function notice(state, entry) {
  state.notices = [...(state.notices ?? []), { ...entry, at: Date.now() }].slice(-20)
}

/**
 * Everything main.mjs does before dsh boots. Returns what it needs to launch dsh and the
 * hooks to call at the outcome. Never throws for a damaged state file: a phone must boot.
 */
export function prepareBoot(env = process.env) {
  const p = paths(env)
  mkdirSync(p.android, { recursive: true })
  const state = readState(p)
  // Notices are per boot: the app reads them from android/ext/list after this start.
  state.notices = []
  const journal = readJson(p.journal, { boots: [] })
  if (!Array.isArray(journal.boots)) journal.boots = []
  const manifest = readManifest(p)
  let bundles = bundlesOf(manifest)
  const nodeModules = join(p.profile, 'node_modules')
  let changed = false
  const suspend = (name, reason, message) => {
    state.suspended[name] = { reason, at: Date.now(), ...message ? { message: String(message).slice(0, 500) } : {} }
    bundles = bundles.filter(b => b !== name)
    changed = true
  }

  // 1. a fatal crash of the last run, attributed to one third-party bundle by its stack
  const crash = readJson(p.crash, undefined)
  let explained = false
  if (crash !== undefined && crash.handled !== true) {
    const hit = attributeCrash(crash.stack, bundles, nodeModules)
    if (hit !== undefined) {
      suspend(hit.bundle, 'crash', crash.message)
      notice(state, { kind: 'suspended', name: hit.bundle, code: 'crash-suspended', message: crash.message ?? '' })
      explained = true
    }
    writeJson(p.crash, { ...crash, handled: true, attributedTo: hit?.bundle ?? null })
  }

  // 2. safe mode: two boots in a row never became ready (or the app asks for it)
  const trailing = (() => { let n = 0; for (const b of [...journal.boots].reverse()) { if (b.phase === 'booting') n += 1; else break } return n })()
  const thirdParty = bundles.filter(isThirdParty)
  const forced = env.DSH_ANDROID_SAFE_MODE === '1'
  if (!explained && thirdParty.length > 0 && (forced || trailing >= SAFE_MODE_AFTER)) {
    state.safeMode = { active: true, at: Date.now(), savedBundles: [...bundles], reason: forced ? 'requested' : 'boot-failures' }
    for (const name of thirdParty) suspend(name, 'safe-mode')
    notice(state, { kind: 'safe-mode', code: 'safe-mode', count: thirdParty.length, message: '' })
  }
  if (explained) journal.boots = journal.boots.map(b => b.phase === 'booting' ? { ...b, phase: 'failed' } : b)

  if (changed && manifest !== undefined) writeBundles(manifest, bundles, p)

  // 3. profile shape: pnpm settings, gate, app layer
  let migrated
  try {
    if (manifest !== undefined) preparePnpmProject(p.profile, p)
    migrated = migrateAppLayer(p)
  } catch (error) {
    process.stderr.write(`[android-extensions] profile preparation failed: ${error?.message ?? error}\n`)
  }

  // 4. journal
  journal.boots = [...journal.boots, { phase: 'booting', at: Date.now(), pid: process.pid, bundles }].slice(-JOURNAL_KEEP)
  writeJson(p.journal, journal)
  writeState(state, p)

  return {
    paths: p,
    patchFiles: existsSync(p.overlay) ? [p.overlay] : [],
    packageManager: packageManager(p, env),
    migrated,
    state,
  }
}

/** Mark the current boot in the journal (`ready` after dsh booted, `stopped` on a clean stop before that). */
export function markBoot(phase, p = paths()) {
  const journal = readJson(p.journal, { boots: [] })
  const boots = Array.isArray(journal.boots) ? journal.boots : []
  const mine = boots.findLastIndex(b => b.pid === process.pid && b.phase === 'booting')
  if (mine < 0) return
  boots[mine] = { ...boots[mine], phase, [`${phase}At`]: Date.now() }
  writeJson(p.journal, { ...journal, boots })
}

/**
 * Record the error that kills the process. dsh's fail-loud handler turns an uncaught exception
 * or unexpected rejection into exit(1); the last error seen is written at exit, so a rejection
 * dsh tolerates (activation failures it already reported) leaves no false crash record.
 */
export function installCrashRecorder(p = paths()) {
  let last
  const remember = (error, origin) => {
    last = { origin, message: String(error?.message ?? error).slice(0, 2000), stack: String(error?.stack ?? '').slice(0, 20000), at: Date.now() }
  }
  process.on('uncaughtExceptionMonitor', (error, origin) => remember(error, origin))
  // A listener here does not change Node's policy: dsh's fail-loud listener decides the exit.
  process.on('unhandledRejection', error => { if (last === undefined) remember(error, 'unhandledRejection') })
  process.on('exit', code => {
    if (code === 0 || last === undefined) return
    try {
      const nodeModules = join(p.profile, 'node_modules')
      writeJson(p.crash, { ...last, code, packages: packagesOnStack(last.stack, nodeModules) })
    } catch {}
  })
}

